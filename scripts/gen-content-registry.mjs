import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generates src/content/articles/registry.generated.ts — static imports of
 * every article JSON. Article reads fall back to this registry when there is no
 * filesystem (Cloudflare Workers); locally they still read the files directly,
 * so editing is unaffected. Runs automatically via the predev/prebuild npm
 * hooks, so adding an article JSON is all it takes — no manual index edits.
 */

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src", "content", "articles");
const out = path.join(dir, "registry.generated.ts");

const files = (await fs.readdir(dir))
  .filter((f) => f.endsWith(".json"))
  .sort();

const lines = [
  "// AUTO-GENERATED by scripts/gen-content-registry.mjs — do not edit by hand.",
  "// Regenerated by the predev/prebuild npm hooks.",
  "// Static article imports so reads work on Cloudflare Workers (no runtime fs).",
  'import type { Article } from "@/lib/articles/types";',
];

const ids = files.map((_, i) => `a${i}`);
files.forEach((f, i) => lines.push(`import ${ids[i]} from "@/content/articles/${f}";`));

lines.push("");
lines.push(`export const ALL_ARTICLES = [${ids.join(", ")}] as unknown as Article[];`);
lines.push("");

await fs.writeFile(out, lines.join("\n"), "utf8");
console.log(`[gen-content] wrote ${files.length} article(s) to registry.generated.ts`);
